def calculate_calories():
    print("--- Калькулятор калорий ---")
    
    # Сбор данных
    gender = input("Введите ваш пол (М/Ж): ").strip().lower()
    age = int(input("Введите ваш возраст: "))
    weight = float(input("Введите ваш вес в кг: "))
    height = float(input("Введите ваш рост в см: "))
    
    print("\nВыберите уровень активности:")
    print("1. Минимальная (сидячая работа, без тренировок)")
    print("2. Небольшая (1-3 тренировки в неделю)")
    print("3. Средняя (3-5 тренировок в неделю)")
    print("4. Высокая (6-7 тренировок в неделю)")
    print("5. Очень высокая (физическая работа + тренировки)")
    activity = input("Введите номер (1-5): ")
    
    print("\nВаша цель:")
    print("1. Похудеть")
    print("2. Сохранить вес")
    print("3. Набрать массу")
    goal = input("Введите номер (1-3): ")
    
    # Расчет базового обмена веществ (BMR) по формуле Миффлина-Сан Жеора
    if gender == 'м' or gender == 'm':
        bmr = (10 * weight) + (6.25 * height) - (5 * age) + 5
    else:
        bmr = (10 * weight) + (6.25 * height) - (5 * age) - 161
        
    # Коэффициенты активности
    if activity == '1': factor = 1.2
    elif activity == '2': factor = 1.375
    elif activity == '3': factor = 1.55
    elif activity == '4': factor = 1.725
    else: factor = 1.9
    
    # Суточный расход (TDEE)
    tdee = bmr * factor
    
    print("\n" + "="*30)
    print(f"Ваш базовый обмен веществ (BMR): {round(bmr)} ккал")
    print(f"Ваш суточный расход (TDEE): {round(tdee)} ккал")
    print("="*30)
    
    # Выдача рекомендаций
    if goal == '1': # Похудение
        print("\nВарианты для похудения:")
        
        slow_deficit = tdee * 0.90
        print(f"1. Медленный (дефицит < 10%): {round(slow_deficit)} ккал. Безопасный и устойчивый результат.")
        
        optimal_deficit = tdee * 0.85
        print(f"2. Оптимальный (дефицит 10-20%): {round(optimal_deficit)} ккал. Рекомендуемый вариант.")
        
        aggressive_deficit = tdee * 0.75
        print(f"3. Агрессивный (дефицит > 20%): {round(aggressive_deficit)} ккал.")
        print("⚠️ ВНИМАНИЕ: Агрессивный дефицит не рекомендуется! Это может привести к срыву, потере мышечной массы и замедлению обмена веществ. Лучше выбрать оптимальный или медленный вариант.")
        
    elif goal == '3': # Набор массы
        print("\nВарианты для набора массы:")
        surplus = tdee * 1.15
        print(f"1. Рекомендуемый профицит (+15%): {round(surplus)} ккал. Для чистого набора массы.")
        print("Совет: набирайте вес постепенно, чтобы избежать лишнего жира.")
    else:
        print("\nДля сохранения веса придерживайтесь вашей нормы TDEE.")

if __name__ == "__main__":
    calculate_calories()